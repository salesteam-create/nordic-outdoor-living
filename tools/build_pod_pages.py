"""Build pod-good.html, pod-better.html and pod-best.html.

Each page = the head, icons and footer from index.html (v5), a page header, missing icons from templates/shell-v3.html
+ templates/pod-main.html with the POD's details filled in.
Run from the repo root after changing index.html's header/footer or the template:

    python3 tools/build_pod_pages.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PODS = [
    {"id": "good", "num": 1, "name": "Good", "shot": "POD1-01", "low": 9900,
     "desc": "NOL POD 1 Good: compact outdoor kitchen with sink, BBQ and glass-door fridge, short-height shell and manual roof. Delivered across the US."},
    {"id": "better", "num": 2, "name": "Better", "shot": "POD2-01", "low": 14900,
     "desc": "NOL POD 2 Better: full-height outdoor kitchen with motorized roof, control module, LED lighting, sink, BBQ, fridge and storage. Delivered across the US."},
    {"id": "best", "num": 3, "name": "Best", "shot": "POD3-01", "low": 19900,
     "desc": "NOL POD 3 Best: our most complete outdoor kitchen with motorized roof, speakers, fan, heater, two storage cabinets, sink, BBQ and fridge."},
]


def relink(html):
    html = re.sub(r'(<a\b[^>]*?href=")#top"', r'\1index.html"', html)
    return re.sub(r'(<a\b[^>]*?href=")#(?!i-)', r'\1index.html#', html)


NAV = """<header class="hd solid" id="hd">
  <a class="mark" href="index.html" aria-label="Nordic Outdoor Living home">NOL<span>Nordic Outdoor Living</span></a>
  <nav aria-label="Page">
    <a href="#product">Overview</a>
    <a href="#kit">In the kit</a>
    <a href="#compare-tiers">Compare</a>
    <a href="#specs">Specs</a>
    <a href="#faq">FAQ</a>
  </nav>
  <a class="btn btn-dark btn-sm" href="#product" data-cta="header_reserve">Reserve</a>
</header>
"""

BUYBAR = """<div class="buy pbuy" id="buybar" aria-hidden="true">
  <img id="barImg" alt="">
  <span><b id="barTitle"></b> <span id="barPrice"></span><span id="barFin" class="muted"></span></span>
  <a class="btn btn-dark btn-sm" href="#product" data-cta="buybar_reserve" tabindex="-1">Reserve</a>
</div>
"""


def main():
    home = (ROOT / "index.html").read_text()  # v5 homepage: head, icons and footer
    v3 = (ROOT / "templates" / "shell-v3.html").read_text()  # extra icons the POD pages use
    template = (ROOT / "templates" / "pod-main.html").read_text()

    head = home[:home.index('<script type="importmap">')]
    head += '<link rel="stylesheet" href="assets/css/pod.css">\n{{LD}}\n</head>\n'
    sprite = home[home.index("<svg width=\"0\""):home.index("</defs>")]
    have = set(re.findall(r'<symbol id="(i-[\w-]+)"', sprite))
    extra = [m.group(0) for m in re.finditer(r'<symbol id="(i-[\w-]+)".*?</symbol>', v3, re.S) if m.group(1) not in have]
    sprite += "".join("    " + x + "\n" for x in extra) + "  </defs>\n</svg>\n\n"
    foot = relink(home[home.index('<footer class="ft">'):home.index("</footer>") + len("</footer>")]) + "\n\n"

    for p in PODS:
        img = f"assets/pods/{p['id']}.jpg"
        ld = {"@context": "https://schema.org", "@type": "Product", "name": f"NOL POD {p['num']} {p['name']}",
              "brand": {"@type": "Brand", "name": "Nordic Outdoor Living"}, "description": p["desc"], "image": [img],
              "offers": {"@type": "Offer", "priceCurrency": "USD", "price": str(p["low"]), "availability": "https://schema.org/PreOrder"}}
        h = head.replace("{{LD}}", '<script type="application/ld+json">\n' + json.dumps(ld) + "\n</script>")
        h = re.sub(r"<title>.*?</title>", f"<title>NOL {p['name']} Outdoor Kitchen POD | Nordic Outdoor Living</title>", h)
        h = re.sub(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{p["desc"]}">', h)
        h = re.sub(r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="https://nolshop.com/products/nol-pod-{p["id"]}">', h)
        h = re.sub(r'<meta property="og:type" content="[^"]*">', '<meta property="og:type" content="product">', h)
        h = re.sub(r'<meta property="og:image" content="[^"]*">', f'<meta property="og:image" content="{img}">', h)
        h = re.sub(r'<meta property="og:title" content="[^"]*">', f'<meta property="og:title" content="NOL {p["name"]} outdoor kitchen POD">', h)
        h = re.sub(r'<meta property="og:description" content="[^"]*">', f'<meta property="og:description" content="{p["desc"]}">', h)
        main_html = template.replace("{{NAME}}", p["name"]).replace("{{IMG}}", img).replace("{{SHOT}}", p["shot"])
        page = (h + f'<body data-pod="{p["id"]}">\n\n' + sprite + NAV + "\n" + main_html + "\n" + foot + BUYBAR + "\n" +
                '<script src="assets/js/catalog.js"></script>\n<script src="assets/js/site.js"></script>\n'
                '<script src="assets/js/configurator.js"></script>\n<script src="assets/js/pod-page.js"></script>\n</body>\n</html>\n')
        page = page.replace("<!doctype html>\n", "<!doctype html>\n<!-- Generated by tools/build_pod_pages.py from index.html and templates/pod-main.html. Edit those, then rebuild. -->\n", 1)
        (ROOT / f"pod-{p['id']}.html").write_text(page)
        print("wrote", f"pod-{p['id']}.html")

    # Old links (product.html?tier=good|better|best) land on the matching POD page
    (ROOT / "product.html").write_text("""<!doctype html>
<meta charset="utf-8"><meta name="robots" content="noindex"><title>NOL PODs</title>
<script>
var t = new URLSearchParams(location.search).get("tier");
var map = { good: "good", better: "better", best: "best", premium: "good", signature: "better", exclusive: "best" };
location.replace("pod-" + (map[t] || "better") + ".html");
</script>
<a href="pod-better.html">Continue to the NOL PODs</a>
""")
    print("wrote product.html (redirect)")


if __name__ == "__main__":
    main()
